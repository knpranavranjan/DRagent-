function outPath = patientSlip(result, opts)
%PATIENTSLIP  The single page the patient takes home.
%
%   p = ophira.report.patientSlip(result)
%   p = ophira.report.patientSlip(result, Context=ctx, Out="slip.html")
%
%   WHAT THIS IS, AND WHAT IT DELIBERATELY IS NOT
%
%   Not a shrunken clinician report. The patient needs to know what to do,
%   by when, and what would mean "come back sooner". Grades, probabilities,
%   Dice coefficients and model versions are noise to that purpose and can
%   be actively harmful -- "grade 2 of 4" reads as a severity score a
%   patient will compare with someone else's.
%
%   SO:
%     - no grade, no probability, no model name, no percentage
%     - one action, in plain words, with a time attached
%     - the red-flag symptoms are ALWAYS listed, including for a clear
%       result, because the commonest harm in screening is a patient who
%       was told they were fine and therefore ignored new symptoms
%     - it never says "you do not have diabetic retinopathy"
%
%   THE LAST POINT MATTERS. A screening pass means "nothing needing
%   referral was visible in today's photograph". It is not a negative
%   diagnosis, and at an uncalibrated site it is a considerably weaker
%   statement than that. The slip is worded to survive being read on its
%   own, months later.

arguments
    result struct
    opts.Context struct = struct()
    opts.Out (1,1) string = ""
    opts.ClinicName (1,1) string = ""
end

if opts.Out == ""
    id = "encounter";
    if isfield(opts.Context,'session') && isfield(opts.Context.session,'session_id')
        id = string(opts.Context.session.session_id);
    end
    opts.Out = ophira.projectRoot("artifacts","reports", id + "_patient.html");
end
d = fileparts(opts.Out);
if ~isfolder(d); mkdir(d); end

action = string(result.decision.action);
[headline, body, when, tone] = wording(action);

h = htmlHead("Your eye screening");
autoPrint = "<script>if(new URLSearchParams(location.search).get('print')){window.addEventListener('load',function(){setTimeout(function(){window.print();},250);});}</script>";
h = h + "<body><main>";

if opts.ClinicName ~= ""
    h = h + sprintf("<div class='clinic'>%s</div>", esc(opts.ClinicName));
end
h = h + "<h1>Your eye screening</h1>";
h = h + sprintf("<p class='date'>%s</p>", ...
        esc(string(datetime("now","Format","d MMMM uuuu"))));

h = h + sprintf("<section class='res %s'>", tone);
h = h + sprintf("<div class='what'>%s</div>", esc(headline));
h = h + sprintf("<p class='body'>%s</p>", esc(body));
h = h + sprintf("<p class='when'><b>%s</b></p>", esc(when));
h = h + "</section>";

% Always present, whatever the result.
h = h + "<h2>Go to a doctor straight away if you notice</h2><ul class='flags'>";
for f = ["Sudden loss of vision in one or both eyes" ...
         "Sudden blurring that does not clear" ...
         "A curtain or shadow across your sight" ...
         "Many new floating spots or flashes of light" ...
         "Pain or redness in the eye"]
    h = h + sprintf("<li>%s</li>", esc(f));
end
h = h + "</ul>";
h = h + "<p class='note'>Do not wait for your next appointment if any of these happen.</p>";

h = h + "<h2>What this check did and did not do</h2>";
h = h + "<p class='small'>A photograph was taken of the back of each eye and " + ...
        "checked by a computer system, then reviewed by clinic staff. " + ...
        "It looked only for changes caused by diabetes. " + ...
        "It did not test for glaucoma, cataract, or other eye conditions, " + ...
        "and it is not a full eye examination. " + ...
        "Keep taking your diabetes treatment and attend your regular check-ups.</p>";

h = h + "<div class='sign'><div><span>Clinic staff</span></div>" + ...
        "<div><span>Date</span></div></div>";
h = h + "</main>" + autoPrint + "</body></html>";

fid = fopen(opts.Out, "w", "n", "UTF-8");
fwrite(fid, h);
fclose(fid);
outPath = opts.Out;
end

%% ========================================================================
function [headline, body, when, tone] = wording(action)
switch action
    case "URGENT"
        headline = "You need to be seen by an eye doctor urgently";
        body     = ["Today's check found something that needs a specialist to " ...
                    "look at it quickly. This does not mean you will lose your " ...
                    "sight, but it should not wait."];
        when     = "Go to the eye clinic within 1 week. Take this paper with you.";
        tone     = "urgent";

    case "REFERRAL"
        headline = "You need an appointment with an eye doctor";
        body     = ["Today's check found changes at the back of your eye that " ...
                    "a specialist should examine. Changes like these are common " ...
                    "in people with diabetes and are usually treatable when found early."];
        when     = "You will be given an eye clinic appointment. Take this paper with you.";
        tone     = "refer";

    case "HUMAN REVIEW"
        headline = "Your photographs need a closer look";
        body     = ["The computer system was not confident enough about today's " ...
                    "photographs to give a result on its own, so a clinician will " ...
                    "review them. This is a normal part of the check and does not " ...
                    "mean something is wrong."];
        when     = "The clinic will contact you with the result.";
        tone     = "review";

    case "RECAPTURE"
        headline = "Your photographs need to be taken again";
        body     = ["The pictures taken today were not clear enough to check " ...
                    "properly. This is usually about the lighting or a reflection, " ...
                    "not about your eyes."];
        when     = "Please have the photographs taken again before you leave, " + ...
                   "or book another visit as soon as you can.";
        tone     = "again";

    otherwise   % ROUTINE
        headline = "No changes needing treatment were seen today";
        body     = ["Today's photographs did not show signs of diabetes affecting " ...
                    "your eyes that need treatment right now. This check looks at " ...
                    "one photograph of each eye on one day, so it cannot rule out " ...
                    "every problem, and eyes can change between visits."];
        when     = "Come back for your next screening in 12 months, or sooner if advised.";
        tone     = "clear";
end
headline = string(strjoin(cellstr(headline), " "));
body     = string(strjoin(cellstr(body), " "));
when     = string(when);
end

function s = esc(t)
s = string(t);
s = replace(s, "&", "&amp;");
s = replace(s, "<", "&lt;");
s = replace(s, ">", "&gt;");
end

